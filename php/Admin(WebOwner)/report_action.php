<?php
require_once __DIR__ . '/admin_common.php';
require_once __DIR__ . '/user_account_common.php';

if (session_status() !== PHP_SESSION_ACTIVE) {
    session_start();
}

$currentUser = admin_require_staff();

global $conn;
$action = strtolower(trim((string) ($_POST['action'] ?? $_GET['action'] ?? '')));

if ($action === 'download') {
    $reportId = (int) ($_GET['report_id'] ?? $_GET['id'] ?? 0);
    if ($reportId <= 0 || !hq_db_available()) {
        http_response_code(400);
        exit('Invalid report request.');
    }

    $statement = $conn->prepare(
        'SELECT p.report_id, p.short_summery, p.message, p.importance, p.created_at, u.user_name, r.role_name
         FROM report p
         LEFT JOIN users u ON u.user_id = p.user_id
         LEFT JOIN roles r ON r.role_id = p.role_id
         WHERE p.report_id = ? LIMIT 1'
    );
    if (!$statement) {
        http_response_code(500);
        exit('The report could not be loaded.');
    }
    $statement->bind_param('i', $reportId);
    $statement->execute();
    $report = $statement->get_result()?->fetch_assoc();
    $statement->close();
    if (!$report) {
        http_response_code(404);
        exit('Report not found.');
    }

    $metadata = admin_report_metadata((string) $report['message']);
    $scopeLabel = admin_scope_label((string) $metadata['scope']);
    $format = (string) $metadata['format'];
    $safeName = preg_replace('/[^a-zA-Z0-9_-]+/', '-', (string) $report['short_summery']) ?: 'report';

    if ($format === 'csv') {
        header('Content-Type: text/csv; charset=UTF-8');
        header('Content-Disposition: attachment; filename="' . $safeName . '-' . $reportId . '.csv"');
        $output = fopen('php://output', 'w');
        fputcsv($output, ['Report ID', 'Title', 'Scope', 'Importance', 'Generated By', 'Created At', 'Summary'], ',', '"', '\\');
        fputcsv($output, [$reportId, $report['short_summery'], $scopeLabel, $report['importance'], $report['user_name'] ?: 'System', $report['created_at'], $metadata['summary']], ',', '"', '\\');
        fclose($output);
        exit;
    }

    // The database has no PDF library or binary report column. This is a
    // print-ready HTML report that can be saved as PDF from the browser.
    header('Content-Type: text/html; charset=UTF-8');
    header('Content-Disposition: attachment; filename="' . $safeName . '-' . $reportId . '.html"');
    echo '<!doctype html><html><head><meta charset="utf-8"><title>' . hq_escape((string) $report['short_summery']) . '</title><style>body{font-family:Arial,sans-serif;max-width:900px;margin:40px auto;color:#152033}h1{margin-bottom:4px}.meta{color:#58677d;margin-bottom:24px}.summary{white-space:pre-wrap;border:1px solid #d8e1eb;padding:18px;border-radius:8px}</style></head><body><h1>' . hq_escape((string) $report['short_summery']) . '</h1><div class="meta">Report #' . $reportId . ' · ' . hq_escape($scopeLabel) . ' · Generated ' . hq_escape(admin_date((string) $report['created_at'])) . '</div><div class="summary">' . hq_escape((string) $metadata['summary']) . '</div><script>window.print();</script></body></html>';
    exit;
}

if ($_SERVER['REQUEST_METHOD'] !== 'POST') {
    admin_redirect('view_report.php');
}

if ($action === 'delete') {
    $reportId = (int) ($_POST['report_id'] ?? 0);
    if ($reportId <= 0) {
        admin_flash('danger', 'The selected report is invalid.');
        admin_redirect('view_report.php');
    }
    $isAdmin = admin_is_admin($currentUser);
    $statement = $isAdmin
        ? $conn->prepare('DELETE FROM report WHERE report_id = ?')
        : $conn->prepare('DELETE FROM report WHERE report_id = ? AND user_id = ?');
    if (!$statement) {
        admin_flash('danger', 'The report could not be deleted.');
        admin_redirect('view_report.php');
    }
    if ($isAdmin) {
        $statement->bind_param('i', $reportId);
    } else {
        $currentUserId = (int) $currentUser['user_id'];
        $statement->bind_param('ii', $reportId, $currentUserId);
    }
    $success = $statement->execute();
    $deleted = $statement->affected_rows;
    $statement->close();
    if (!$success || $deleted < 1) {
        admin_flash('danger', 'The report was not found or could not be deleted.');
        admin_redirect('view_report.php');
    }
    admin_record_log((int) $currentUser['user_id'], 'Deleted report #' . $reportId . '.');
    admin_flash('success', 'Report #' . $reportId . ' was deleted.');
    admin_redirect('view_report.php');
}

if ($action === 'generate') {
    if (admin_is_admin($currentUser)) {
        admin_flash('danger', 'Report generation is not available to Admin accounts.');
        admin_redirect('view_report.php');
    }

    $title = trim((string) ($_POST['report_title'] ?? ''));
    $scope = strtolower(trim((string) ($_POST['scope'] ?? '')));
    $startDate = trim((string) ($_POST['start_date'] ?? ''));
    $endDate = trim((string) ($_POST['end_date'] ?? ''));
    $format = strtolower(trim((string) ($_POST['format'] ?? '')));
    $allowedScopes = ['hq_performance', 'stations', 'requests', 'system'];
    $allowedFormats = ['pdf', 'csv'];

    if ($title === '' || strlen($title) > 255 || !in_array($scope, $allowedScopes, true) || !in_array($format, $allowedFormats, true)) {
        admin_flash('danger', 'Please provide a valid report title, data scope, and export format.');
        admin_redirect('view_report.php');
    }
    if (!admin_is_admin($currentUser) && $scope === 'system') {
        admin_flash('danger', 'Only an Admin can generate a system security and audit report.');
        admin_redirect('view_report.php');
    }
    $start = DateTime::createFromFormat('!Y-m-d', $startDate);
    $end = DateTime::createFromFormat('!Y-m-d', $endDate);
    $dateErrors = DateTime::getLastErrors();
    if (!$start || !$end || ($dateErrors !== false && ($dateErrors['warning_count'] > 0 || $dateErrors['error_count'] > 0)) || $startDate === '' || $endDate === '' || $startDate > $endDate) {
        admin_flash('danger', 'Please provide a valid report date range.');
        admin_redirect('view_report.php');
    }

    $summary = '';
    if ($scope === 'hq_performance') {
                $summaryQuery = $conn->query("SELECT COUNT(*) AS total,
                        COALESCE(SUM((SELECT COUNT(*) FROM business_account_scope bas
                                                    INNER JOIN users u ON u.user_id = bas.user_id
                                                    WHERE bas.headquarter_id = h.headquarter_id
                                                        AND LOWER(u.status) IN (0x617070726f766564,0x616374697665))), 0) AS active
                        FROM headquarter h");
        $summaryRow = $summaryQuery?->fetch_assoc() ?: ['total' => 0, 'active' => 0];
        $summary = 'Company records: ' . (int) $summaryRow['total'] . '; active linked accounts: ' . (int) $summaryRow['active'];
    } elseif ($scope === 'stations') {
        // Always count from `branches` (not a legacy stations view).
        $summaryQuery = $conn->query(
            "SELECT COUNT(*) AS total,
                    COALESCE(SUM(CASE WHEN LOWER(TRIM(status)) IN ('active', 'approved') THEN 1 ELSE 0 END), 0) AS active,
                    COALESCE(SUM(CASE WHEN LOWER(TRIM(status)) IN ('closed', 'suspended', 'offline') THEN 1 ELSE 0 END), 0) AS inactive
             FROM branches"
        );
        $summaryRow = $summaryQuery?->fetch_assoc() ?: ['total' => 0, 'active' => 0, 'inactive' => 0];
        $summary = 'Station records (branches): ' . (int) $summaryRow['total']
            . '; active: ' . (int) $summaryRow['active']
            . '; inactive/closed: ' . (int) $summaryRow['inactive'];
    } elseif ($scope === 'requests') {
        $summaryQuery = $conn->query('SELECT COUNT(*) AS total, COALESCE(SUM(status=0x70656e64696e67),0) AS pending, COALESCE(SUM(status=0x617070726f766564),0) AS approved, COALESCE(SUM(status IN (0x72656a6563746564,0x666c6167676564)),0) AS declined FROM system_requests');
        $summaryRow = $summaryQuery?->fetch_assoc() ?: ['total' => 0, 'pending' => 0, 'approved' => 0, 'declined' => 0];
        $pendingAccounts = pending_account_count();
        $summary = 'Requests: ' . ((int) $summaryRow['total'] + $pendingAccounts)
            . '; pending: ' . ((int) $summaryRow['pending'] + $pendingAccounts)
            . '; approved: ' . (int) $summaryRow['approved']
            . '; declined/flagged: ' . (int) $summaryRow['declined'];
    } else {
        $summaryQuery = $conn->query('SELECT COUNT(*) AS total FROM log');
        $summary = 'Audit log entries: ' . (int) (($summaryQuery?->fetch_assoc()['total'] ?? 0));
    }

    $message = sprintf('[scope=%s][format=%s][start=%s][end=%s] %s', $scope, $format, $startDate, $endDate, $summary);
    $userId = (int) $currentUser['user_id'];
    $accountId = map_pump_account_identity_ensure($pdo, 'user', $userId);
    $roleId = (int) ($currentUser['effective_role_id'] ?? $currentUser['role_id']);
    $importance = 'normal';
    $statement = $conn->prepare('INSERT INTO report (user_id, submitted_by_account_id, role_id, importance, short_summery, message, created_at) VALUES (?, ?, ?, ?, ?, ?, NOW())');
    if (!$statement) {
        admin_flash('danger', 'The report could not be prepared.');
        admin_redirect('view_report.php');
    }
    $statement->bind_param('iiisss', $userId, $accountId, $roleId, $importance, $title, $message);
    if (!$statement->execute()) {
        $statement->close();
        admin_flash('danger', 'The report could not be generated.');
        admin_redirect('view_report.php');
    }
    $reportId = (int) $statement->insert_id;
    $statement->close();
    admin_record_log($userId, 'Generated report #' . $reportId . ' (' . $scope . ').');
    admin_flash('success', 'Report #' . $reportId . ' was generated successfully.');
    admin_redirect('view_report.php');
}

admin_flash('danger', 'The requested report action is not supported.');
admin_redirect('view_report.php');
